// Compiler for Usagi Electric UE-1

// UE-1 UE14500 processor instruction set and opcodes:

// --------------------------------------------------------------------------------------
// |	0000 | NOP0 	| NO CHANGE IN REGISTERS	| RR -> RR, FLG0^		|
// --------------------------------------------------------------------------------------
// |	0001 | LD 	| LOAD RESULT REGISTER		| DATA -> RR			|
// --------------------------------------------------------------------------------------
// |	0010 | ADD	| ADD RR AND DATA		| DATA + RR -> RR		|
// --------------------------------------------------------------------------------------
// |	0011 | SUB	| SUBTRACT RR AND DATA		| DATA - RR -> RR		|
// --------------------------------------------------------------------------------------
// |	0100 | ONE	| FORCE 1 INTO RR		| 1 -> RR, 0 -> CAR		|
// --------------------------------------------------------------------------------------
// |	0101 | NAND	| NAND DATA AND RR		| RR.DATA -> RR			|
// --------------------------------------------------------------------------------------
// |	0110 | OR	| OR DATA AND RR		| RR||DATA -> RR		|
// --------------------------------------------------------------------------------------
// |	0111 | XOR	| XOR DATA AND RR		| IF RR != DATA, 1 -> RR	|
// --------------------------------------------------------------------------------------
// |	1000 | STO	| STORE RR			| RR -> DATA, WRT^		|
// --------------------------------------------------------------------------------------
// |	1001 | STOC	| STORE COMPLIMENT		| QRR -> DATA, WRT^		|
// --------------------------------------------------------------------------------------
// |	1010 | IEN	| INPUT ENABLE			| DATA -> IEN			|
// --------------------------------------------------------------------------------------
// |	1011 | OEN	| OUTPUT ENABLE			| DATA -> OEN			|
// --------------------------------------------------------------------------------------
// |	1100 | IOC	| INPUT OUTPUT CONTROL		| IOC^				|
// --------------------------------------------------------------------------------------
// |	1101 | RTN	| RETURN FROM SUBROUTINE	| RTN^, SKIP NEXT INSTRUCTION	|
// --------------------------------------------------------------------------------------
// |	1110 | SKZ	| SKIP IF ZERO			| RR=0,SKIP NEXT INSTRUCTION	|
// --------------------------------------------------------------------------------------
// |	1111 | NOPF	| NO CHANGE IN REGISTERS	| RR -> RR, FLGF^		|
// --------------------------------------------------------------------------------------

